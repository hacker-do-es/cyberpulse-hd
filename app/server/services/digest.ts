/* What goes into one company's digest for one channel, and how it reads:
   news fetched since the channel's last successful delivery that matches the
   company's stack, at or above the channel's minimum severity, never
   repeating an article. */

export const SEVERITIES = ['low', 'medium', 'high', 'critical'] as const;
const SEVERITY_RANK: Record<string, number> = { low: 0, medium: 1, high: 2, critical: 3 };

/* How far back a brand-new channel looks on its first run. */
const FIRST_RUN_LOOKBACK_HOURS = 24;
/* Never resurface old articles from a feed that was just added. */
const MAX_ARTICLE_AGE_DAYS = 14;
/* Verified-only channels also look back this far: an article whose CVE
   data arrived late, or that became relevant when a version was entered,
   still gets sent once (channel_sent_articles prevents repeats). */
const VERIFIED_LOOKBACK_DAYS = 7;
/* How long a digest run may wait for missing CVE data. */
const CVE_FETCH_BUDGET_MS = 60_000;

