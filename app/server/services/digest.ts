export function digestText(channel: ChannelRow, tenant: Pick<TenantRow, 'name' | 'language'>, items: Candidate[], summary: string | null): string {
  const labels = labelsFor(tenant.language);
  const digestItems: DigestItem[] = items.map((i) => toReportItem(i, labels));
  return renderMessage(channel.type, {
    heading: heading(channel, labels, tenant.name, items.length),
    summary,
    items: digestItems,
    footer: footer(channel, labels),
    labels: reportLabels(labels),
  }).text;
}

/* With custom branding the test doubles as a preview of header and footer. */
export function testText(channel: ChannelRow, tenant: Pick<TenantRow, 'name' | 'language'> | undefined): string {
  const labels = labelsFor(tenant?.language);
  const company = tenant?.name ?? '';
  if (channel.headerText !== null || channel.footerText !== null) {
    return renderTestPreview(channel.type, {
      heading: heading(channel, labels, company, 3),
      body: labels.testCustom(company),
      footer: footer(channel, labels),
    });
  }
  return renderPlain(channel.type, labels.test(company));
}

