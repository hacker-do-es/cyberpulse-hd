type EmailBranding = Pick<ChannelRow, 'headerText' | 'footerText' | 'headerHtml' | 'footerHtml'>;

function emailDigest(channel: EmailBranding, tenant: Pick<TenantRow, 'name' | 'language'> | undefined, count: number, extra: Partial<EmailDigest>): EmailDigest {
  const labels = labelsFor(tenant?.language);
  const company = tenant?.name ?? '';
  return {
    /* The plain header doubles as the subject line. */
    subject: (channel.headerText ? renderHeader(channel.headerText, company, count) : defaultHeading(channel as Partial<ChannelRow>, labels, company, count)).replace(/[\r\n]+/g, ' '),
    company,
    count,
    headerHtml: channel.headerHtml,
    footerHtml: channel.footerHtml,
    defaultFooter: labels.footer,
    summary: null,
    items: [],
    labels: { ...reportLabels(labels), summary: labels.summary },
    ...extra,
  };
}

function toEmail(d: EmailDigest): OutgoingEmail {
  return { subject: d.subject, html: renderEmailHtml(d), text: renderEmailText(d) };
}

export function digestEmail(channel: EmailBranding, tenant: Pick<TenantRow, 'name' | 'language'>, items: Candidate[], summary: string | null): OutgoingEmail {
  return toEmail(emailDigest(channel, tenant, items.length, {
    summary,
    items: items.map((i) => toReportItem(i, labelsFor(tenant.language))),
  }));
}

export function testEmail(channel: EmailBranding, tenant: Pick<TenantRow, 'name' | 'language'> | undefined): OutgoingEmail {
  const labels = labelsFor(tenant?.language);
  return toEmail(emailDigest(channel, tenant, 3, { body: labels.testCustom(tenant?.name ?? '') }));
}

