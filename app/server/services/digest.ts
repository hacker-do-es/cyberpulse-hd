export interface Candidate {
  id: number;
  title: string;
  summary: string;
  source: string;
  severity: string;
  url: string;
  category: string;
  matchedTech: string[];
  matchedStackIds: number[];
  score: number;
  /* Only set for channels that include assets (see withAssets). */
  assets?: AssetRef[];
  /* Verified-only channels: the confirmed version verdict and best CVSS. */
  vuln?: ArticleVuln;
  cvss?: number | null;
  /* Most critical asset this item affects (set when assets are known). */
  tier?: Tier;
}

/* Why a run found nothing to send (recorded in the delivery log). */
export interface SelectionStats {
  matched: number;
  affected: number;
  notAffected: number;
  unverified: number;
  noCve: number;
}

export function isVerifiedOnly(channel: Pick<ChannelRow, 'type' | 'verifiedOnly'>): boolean {
  return channel.type !== 'linkedin' && channel.verifiedOnly !== false;
}

/* The assets a candidate concerns: for verified items only the affected ones. */
function candidateAssets(c: Candidate, links: Map<number, AssetRef[]>): AssetRef[] {
  const all = assetsForStackIds(c.matchedStackIds, links);
  if (!c.vuln) return all;
  const ids = affectedAssetIds(c.vuln);
  return all.filter((a) => ids.has(a.id));
}

/* `assetLinks` (stack row id → assets) is only passed for digest channels
   that filter by asset criticality; LinkedIn never gets it. */
export async function selectCandidates(
  channel: ChannelRow,
  stack: TechStackItem[],
  now = new Date(),
  assetLinks?: Map<number, AssetRef[]>,
  stats?: SelectionStats,
): Promise<Candidate[]> {
  const verified = isVerifiedOnly(channel);
  let since = channel.lastSentAt ?? toSqlUtc(new Date(now.getTime() - FIRST_RUN_LOOKBACK_HOURS * 3600_000));
  if (verified) {
    const lookback = toSqlUtc(new Date(now.getTime() - VERIFIED_LOOKBACK_DAYS * 86400_000));
    if (lookback < since) since = lookback;
  }
  const oldest = toSqlUtc(new Date(now.getTime() - MAX_ARTICLE_AGE_DAYS * 86400_000)).replace(' ', 'T');
  const rows = articleRepository.undeliveredForChannel(channel.id, since, oldest);

  const matches = await matchChunked(
    rows.map((r) => ({ id: String(r.id), title: r.title, summary: r.summary || '', category: r.category ?? 'GENERAL', row: r })),
    stack,
  );

  const minRank = SEVERITY_RANK[channel.minSeverity] ?? 0;
  let candidates: Candidate[] = matches
    .map(({ article: { row }, score, matchedTech, matchedIds }) => ({
      id: row.id,
      title: row.title,
      summary: row.summary || '',
      source: row.source,
      severity: (row.severity || 'low').toLowerCase(),
      url: row.url,
      category: row.category ?? 'GENERAL',
      matchedTech,
      matchedStackIds: matchedIds,
      score,
    }))
    .filter((c) => (SEVERITY_RANK[c.severity] ?? 0) >= minRank);

  if (stats) stats.matched = candidates.length;
  if (verified) candidates = await onlyConfirmed(channel.tenantId, candidates, stats);

  if (assetLinks) {
    candidates = candidates.map((c) => {
      const top = Math.max(-1, ...candidateAssets(c, assetLinks).map((a) => criticalityRank(a.criticality)));
      return { ...c, tier: (['low', 'medium', 'high'][top] ?? 'none') as Tier };
    });
  }
  const TIER_RANK: Record<string, number> = { high: 3, medium: 2, low: 1, none: 0 };
  return candidates
    .filter((c) => {
      if (!assetLinks || !channel.minAssetCriticality) return true;
      const min = criticalityRank(channel.minAssetCriticality);
      return candidateAssets(c, assetLinks).some((a) => criticalityRank(a.criticality) >= min);
    })
    /* Critical assets first, so they survive the max-items cut. */
    .sort((a, b) => (TIER_RANK[b.tier ?? 'none'] - TIER_RANK[a.tier ?? 'none'])
      || (SEVERITY_RANK[b.severity] ?? 0) - (SEVERITY_RANK[a.severity] ?? 0) || (b.cvss ?? -1) - (a.cvss ?? -1) || b.score - a.score)
    .slice(0, Math.max(1, Math.min(channel.maxItems, 50)));
}

/* Keeps the candidates whose CVEs are confirmed to affect an installed
   version, narrowed to the technologies that are affected. Missing CVE data
   is fetched first, within a time budget. */
async function onlyConfirmed(tenantId: number, candidates: Candidate[], stats?: SelectionStats): Promise<Candidate[]> {
  const cves = new Map(candidates.map((c) => [c.id, articleCves(c)]));
  const all = Array.from(new Set(Array.from(cves.values()).flat()));
  if (all.length) {
    try {
      await syncCves(all, Date.now() + CVE_FETCH_BUDGET_MS);
    } catch (err) {
      console.error('[DIGEST] CVE fetch failed:', err);
    }
  }
  const ctx = verdictContext(tenantId, all);
  const out: Candidate[] = [];
  for (const c of candidates) {
    const vuln = evaluateArticle(cves.get(c.id) ?? [], c.matchedStackIds, ctx);
    if (stats) {
      if (vuln.status === 'affected') stats.affected++;
      else if (vuln.status === 'not_affected') stats.notAffected++;
      else if (vuln.status === 'no_cve') stats.noCve++;
      else stats.unverified++;
    }
    if (vuln.status !== 'affected') continue;
    const hit = vuln.units.filter((u) => u.status === 'affected');
    const cvssValues = Array.from(new Set(hit.map((u) => u.cve).filter((x): x is string => !!x)))
      .map((id) => ctx.records.get(id)?.data?.cvss).filter((x): x is number => typeof x === 'number');
    out.push({
      ...c,
      vuln,
      cvss: cvssValues.length ? Math.max(...cvssValues) : null,
      matchedStackIds: Array.from(new Set(hit.map((u) => u.stackId))),
      matchedTech: Array.from(new Set(hit.map((u) => u.technology))),
    });
  }
  return out;
}

export function emptyStats(): SelectionStats {
  return { matched: 0, affected: 0, notAffected: 0, unverified: 0, noCve: 0 };
}

/* Attaches the affected assets to each item. Called only for digest
   channels with include_assets on; never for LinkedIn. */
export function withAssets(items: Candidate[], assetLinks: Map<number, AssetRef[]>): Candidate[] {
  return items.map((i) => ({ ...i, assets: candidateAssets(i, assetLinks) }));
}

/* The channel-neutral item every renderer draws. */
function toReportItem(item: Candidate, labels: Labels): ReportItem {
  const base: ReportItem = {
    title: item.title, url: item.url, source: item.source, severity: item.severity,
    matchedTech: item.matchedTech, assets: assetLabels(item, labels), tier: item.tier,
  };
  if (!item.vuln) return base;
  const fixes = new Map<string, { technology: string; version: string | null; fixedIn?: string }>();
  for (const u of item.vuln.units) {
    if (u.status !== 'affected') continue;
    const key = `${u.technology}|${u.version}`;
    if (!fixes.has(key)) fixes.set(key, { technology: u.technology, version: u.version, ...(u.fixedIn ? { fixedIn: u.fixedIn } : {}) });
  }
  const cves = Array.from(new Set(item.vuln.units.filter((u) => u.status === 'affected' && u.cve).map((u) => u.cve!)));
  return { ...base, cves, cvss: item.cvss ?? null, fixes: Array.from(fixes.values()) };
}

function reportLabels(labels: Labels) {
  return {
    severity: labels.severity, affects: labels.affects, assets: labels.assets,
    tiers: labels.tiers, updateTo: labels.updateTo, inCritical: labels.inCritical, severityCount: labels.severityCount,
  };
}


function assetLabels(item: Candidate, labels: Labels): string[] | undefined {
  if (!item.assets?.length) return undefined;
  return item.assets.map((a) => {
    const crit = labels.criticality[a.criticality] ?? a.criticality;
    // name · hostname · IP (criticality) — hostname/IP omitted when absent.
    const parts = [a.name, a.hostname, a.ip].filter((p): p is string => Boolean(p));
    return `${parts.join(' · ')} (${crit})`;
  });
}

