type Labels = (typeof LABELS)[keyof typeof LABELS];

export function labelsFor(language: string | undefined): Labels {
  return language === 'en' ? LABELS.en : LABELS.es;
}

/* Custom header: {company}/{empresa} and {count}/{n} are filled in. */
export function renderHeader(template: string, company: string, count: number): string {
  return template
    .replace(/\{(company|empresa)\}/gi, company)
    .replace(/\{(count|n)\}/gi, String(count));
}

/* Default title: "N confirmed vulnerabilities" on verified-only channels. */
function defaultHeading(channel: Partial<Pick<ChannelRow, 'type' | 'verifiedOnly'>>, labels: Labels, company: string, count: number): string {
  const verified = channel.type !== undefined && isVerifiedOnly(channel as Pick<ChannelRow, 'type' | 'verifiedOnly'>);
  return verified ? labels.headingVerified(company, count) : labels.heading(company, count);
}

function heading(channel: ChannelRow, labels: Labels, company: string, count: number): string {
  return channel.headerText ? renderHeader(channel.headerText, company, count) : defaultHeading(channel, labels, company, count);
}

/* NULL = default footer, '' = no footer. */
function footer(channel: ChannelRow, labels: Labels): string {
  return channel.footerText ?? labels.footer;
}

