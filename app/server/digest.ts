/* Builds and sends one company's digest to one channel: news fetched since
   the channel's last successful delivery that matches the company's stack,
   at or above the channel's minimum severity, never repeating an article. */

export const SEVERITIES = ['low', 'medium', 'high', 'critical'] as const;
const SEVERITY_RANK: Record<string, number> = { low: 0, medium: 1, high: 2, critical: 3 };

/* How far back a brand-new channel looks on its first run. */
const FIRST_RUN_LOOKBACK_HOURS = 24;
/* Never resurface old articles from a feed that was just added. */
const MAX_ARTICLE_AGE_DAYS = 14;

export interface ChannelRow {
  id: number;
  tenant_id: number;
  name: string;
  type: ChannelType;
  webhook_url: string;
  active: number;
  schedule_type: 'interval' | 'weekly';
  interval_hours: number | null;
  time_of_day: string | null;
  weekdays: string | null;
  min_severity: string;
  max_items: number;
  use_ai: number;
  header_text: string | null;
  footer_text: string | null;
  last_run_at: string | null;
  last_sent_at: string | null;
  next_run_at: string | null;
}

export function channelSchedule(c: Pick<ChannelRow, 'schedule_type' | 'interval_hours' | 'time_of_day' | 'weekdays'>): Schedule {
  return {
    type: c.schedule_type,
    intervalHours: c.interval_hours,
    timeOfDay: c.time_of_day,
    weekdays: parseWeekdays(c.weekdays),
  };
}

