export function rescheduleChannel(channelId: number, from = new Date()): void {
  const db = getDb();
  const row = db.prepare(`
    SELECT c.schedule_type, c.interval_hours, c.time_of_day, c.weekdays, t.timezone
    FROM channels c JOIN tenants t ON t.id = c.tenant_id WHERE c.id = ?
  `).get(channelId) as (Pick<ChannelRow, 'schedule_type' | 'interval_hours' | 'time_of_day' | 'weekdays'> & { timezone: string }) | undefined;
  if (!row) return;
  const next = computeNextRun(channelSchedule(row), from, row.timezone);
  db.prepare(`UPDATE channels SET next_run_at = ? WHERE id = ?`).run(toSqlUtc(next), channelId);
}

export function rescheduleTenant(tenantId: number): void {
  const ids = getDb().prepare(`SELECT id FROM channels WHERE tenant_id = ?`).all(tenantId) as Array<{ id: number }>;
  for (const { id } of ids) rescheduleChannel(id);
}

let tickRunning = false;

/* Called every minute. Advances next_run_at before sending, so a crash or a
   slow webhook can never make the same slot fire twice. */
export async function schedulerTick(now = new Date()): Promise<void> {
  if (tickRunning) return;
  tickRunning = true;
  try {
    const db = getDb();
    const due = db.prepare(`
      SELECT c.id FROM channels c JOIN tenants t ON t.id = c.tenant_id
      WHERE c.active = 1 AND t.active = 1 AND c.next_run_at IS NOT NULL AND c.next_run_at <= ?
      ORDER BY c.next_run_at
    `).all(toSqlUtc(now)) as Array<{ id: number }>;

    for (const { id } of due) {
      rescheduleChannel(id, now);
      try {
        const result = await runChannel(id, 'schedule');
        console.log(`[SCHEDULER] channel ${id}: ${result.status} (${result.detail})`);
      } catch (err) {
        console.error(`[SCHEDULER] channel ${id} failed:`, err);
      }
    }
  } finally {
    tickRunning = false;
  }
}

export function pruneDeliveryHistory(): void {
  const db = getDb();
  db.prepare(`DELETE FROM channel_sent_articles WHERE sent_at < datetime('now', '-60 days')`).run();
  db.prepare(`DELETE FROM deliveries WHERE created_at < datetime('now', '-180 days')`).run();
}
